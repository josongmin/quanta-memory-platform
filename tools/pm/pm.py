#!/usr/bin/env python3
"""Render and lint generated agent guidance using only the Python standard library."""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Union


PM_DIR = Path(__file__).resolve().parent
REPO_ROOT = PM_DIR.parent.parent
BANNER = """<!--
DO NOT EDIT — generated by tools/pm.
Source of truth: tools/pm/sources/**. Edit there, then run
`python3 tools/pm/pm.py sync`.
Hand edits are overwritten and will fail `pm lint`.
-->
"""


class PmError(Exception):
    """Raised for invalid configuration, paths, or usage."""


def _unique_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise PmError(f"duplicate manifest key: {key}")
        result[key] = value
    return result


def _reject_unknown_keys(value: dict[str, object], allowed: set[str], where: str) -> None:
    unknown = sorted(value.keys() - allowed)
    if unknown:
        raise PmError(f"unknown {where} key(s): {', '.join(unknown)}")


FrontmatterValue = Union[str, bool, tuple[str, ...]]


@dataclass(frozen=True)
class Target:
    name: str
    output: str
    title: str
    sections: tuple[str, ...]
    frontmatter: tuple[tuple[str, FrontmatterValue], ...] = ()
    max_lines: int | None = None
    max_bytes: int | None = None


@dataclass(frozen=True)
class Manifest:
    targets: dict[str, Target]
    retired_outputs: tuple[str, ...]


def _safe_relative_path(value: object, *, field: str, target: str) -> str:
    if not isinstance(value, str) or not value:
        raise PmError(f"target '{target}' {field} must be a non-empty string")
    path = PurePosixPath(value)
    if (
        path.is_absolute()
        or path == PurePosixPath(".")
        or ".." in path.parts
        or path.parts[:1] == (".git",)
        or path.as_posix() != value
    ):
        raise PmError(f"target '{target}' {field} escapes its root: {value}")
    return value


def _frontmatter(
    value: object, *, target: str
) -> tuple[tuple[str, FrontmatterValue], ...]:
    if value is None:
        return ()
    if not isinstance(value, dict) or not value:
        raise PmError(f"target '{target}' frontmatter must be a non-empty mapping")

    normalized: list[tuple[str, FrontmatterValue]] = []
    for key, raw in value.items():
        if not isinstance(key, str) or re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]*", key) is None:
            raise PmError(f"target '{target}' has invalid frontmatter key: {key!r}")
        if isinstance(raw, bool):
            normalized.append((key, raw))
        elif isinstance(raw, str) and raw and "\n" not in raw:
            normalized.append((key, raw))
        elif (
            isinstance(raw, list)
            and raw
            and all(isinstance(item, str) and item and "\n" not in item for item in raw)
        ):
            normalized.append((key, tuple(raw)))
        else:
            raise PmError(
                f"target '{target}' frontmatter values must be booleans, "
                "non-empty strings, or non-empty string lists"
            )
    return tuple(normalized)


def _optional_positive_int(value: object, *, field: str, target: str) -> int | None:
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise PmError(f"target '{target}' {field} must be a positive integer")
    return value


def load_manifest(targets_path: Path) -> Manifest:
    if not targets_path.is_file():
        raise PmError(f"targets file not found: {targets_path}")
    try:
        raw = json.loads(targets_path.read_text(encoding="utf-8"), object_pairs_hook=_unique_object)
    except json.JSONDecodeError as error:
        raise PmError(f"invalid targets JSON: {error}") from error
    if isinstance(raw, dict):
        _reject_unknown_keys(raw, {"targets", "retired_outputs"}, "manifest")
    targets_raw = raw.get("targets") if isinstance(raw, dict) else None
    if not isinstance(targets_raw, dict) or not targets_raw:
        raise PmError(f"targets file has no non-empty 'targets' mapping: {targets_path}")

    targets: dict[str, Target] = {}
    outputs: set[str] = set()
    referenced_sources: set[str] = set()
    for name, spec in targets_raw.items():
        if not isinstance(name, str) or not name or not isinstance(spec, dict):
            raise PmError("target names and specifications must be mappings")
        _reject_unknown_keys(
            spec,
            {"output", "title", "sections", "frontmatter", "max_lines", "max_bytes"},
            f"target '{name}'",
        )
        output = _safe_relative_path(spec.get("output"), field="output", target=name)
        title = spec.get("title")
        sections = spec.get("sections")
        if not isinstance(title, str) or not title:
            raise PmError(f"target '{name}' title must be a non-empty string")
        if not isinstance(sections, list) or not sections:
            raise PmError(f"target '{name}' must have a non-empty 'sections' list")
        safe_sections = tuple(
            _safe_relative_path(section, field="section", target=name) for section in sections
        )
        if any(
            PurePosixPath(section).parts[:1] != ("sources",)
            or PurePosixPath(section).suffix != ".md"
            for section in safe_sections
        ):
            raise PmError(f"target '{name}' sections must be Markdown files under sources/")
        if len(set(safe_sections)) != len(safe_sections):
            raise PmError(f"target '{name}' contains duplicate sections")
        if output in outputs:
            raise PmError(f"duplicate generated output: {output}")
        outputs.add(output)
        referenced_sources.update(safe_sections)
        targets[name] = Target(
            name,
            output,
            title,
            safe_sections,
            _frontmatter(spec.get("frontmatter"), target=name),
            _optional_positive_int(spec.get("max_lines"), field="max_lines", target=name),
            _optional_positive_int(spec.get("max_bytes"), field="max_bytes", target=name),
        )

    retired_raw = raw.get("retired_outputs", [])
    if not isinstance(retired_raw, list):
        raise PmError("'retired_outputs' must be a list")
    retired_outputs = tuple(
        _safe_relative_path(value, field="retired output", target="manifest")
        for value in retired_raw
    )
    if len(set(retired_outputs)) != len(retired_outputs):
        raise PmError("retired_outputs contains duplicates")
    overlap = sorted(outputs.intersection(retired_outputs))
    if overlap:
        raise PmError(f"active and retired outputs overlap: {', '.join(overlap)}")

    source_root = targets_path.parent / "sources"
    source_paths = list(source_root.rglob("*.md"))
    symlinked = [path for path in source_paths if path.is_symlink()]
    if symlinked:
        rendered = ", ".join(
            path.relative_to(targets_path.parent).as_posix() for path in symlinked
        )
        raise PmError(f"symlinked source file(s) are not allowed: {rendered}")
    actual_sources = {
        path.relative_to(targets_path.parent).as_posix() for path in source_paths
    }
    orphaned = sorted(actual_sources - referenced_sources)
    if orphaned:
        raise PmError(f"orphaned source file(s): {', '.join(orphaned)}")
    return Manifest(targets, retired_outputs)


def load_targets(targets_path: Path) -> dict[str, Target]:
    """Compatibility helper for callers that need active targets only."""
    return load_manifest(targets_path).targets


def _read_sections(pm_dir: Path, target: Target) -> str:
    chunks: list[str] = []
    source_root = (pm_dir / "sources").resolve()
    for section in target.sections:
        section_path = pm_dir / section
        if section_path.is_symlink() or not section_path.resolve().is_relative_to(source_root):
            raise PmError(
                f"target '{target.name}': source file escapes sources/: {section_path}"
            )
        if not section_path.is_file():
            raise PmError(f"target '{target.name}': missing source file {section_path}")
        chunks.append(section_path.read_text(encoding="utf-8").rstrip("\n"))
    return "\n\n".join(chunks) + "\n"


def render_target(target: Target, pm_dir: Path = PM_DIR) -> str:
    frontmatter = ""
    if target.frontmatter:
        lines = ["---"]
        for key, value in target.frontmatter:
            if isinstance(value, bool):
                rendered = "true" if value else "false"
            else:
                rendered = json.dumps(value, ensure_ascii=False)
            lines.append(f"{key}: {rendered}")
        lines.append("---")
        frontmatter = "\n".join(lines) + "\n"

    rendered = f"{frontmatter}{BANNER}# {target.title}\n\n{_read_sections(pm_dir, target)}"
    line_count = len(rendered.splitlines())
    byte_count = len(rendered.encode("utf-8"))
    if target.max_lines is not None and line_count > target.max_lines:
        raise PmError(
            f"target '{target.name}' exceeds max_lines: {line_count} > {target.max_lines}"
        )
    if target.max_bytes is not None and byte_count > target.max_bytes:
        raise PmError(
            f"target '{target.name}' exceeds max_bytes: {byte_count} > {target.max_bytes}"
        )
    return rendered


def output_path(target: Target, repo_root: Path = REPO_ROOT) -> Path:
    root = repo_root.resolve()
    out = repo_root / target.output
    if out.is_symlink():
        raise PmError(f"target '{target.name}': generated output may not be a symlink: {out}")
    if not out.parent.resolve().is_relative_to(root):
        raise PmError(f"target '{target.name}': generated output escapes repository: {out}")
    return out


def retired_output_path(value: str, repo_root: Path = REPO_ROOT) -> Path:
    root = repo_root.resolve()
    out = repo_root / value
    if not out.parent.resolve().is_relative_to(root):
        raise PmError(f"retired output escapes repository: {out}")
    return out


def sync_target(target: Target, pm_dir: Path, repo_root: Path) -> Path:
    out = output_path(target, repo_root)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_target(target, pm_dir), encoding="utf-8")
    return out


def check_drift(target: Target, pm_dir: Path = PM_DIR, repo_root: Path = REPO_ROOT) -> str:
    out = output_path(target, repo_root)
    if not out.is_file():
        return "missing"
    return "ok" if out.read_text(encoding="utf-8") == render_target(target, pm_dir) else "drift"


def orphaned_generated_outputs(manifest: Manifest, repo_root: Path) -> list[str]:
    """Find generated files whose targets were removed without retiring them."""
    known = {target.output for target in manifest.targets.values()} | set(manifest.retired_outputs)
    marker = BANNER.encode("utf-8")
    orphaned: list[str] = []
    def fail_walk(error: OSError) -> None:
        raise PmError(f"cannot inspect generated outputs: {error}") from error

    for directory, subdirs, files in os.walk(repo_root, onerror=fail_walk):
        subdirs[:] = [
            name for name in subdirs
            if name not in {".git", "target", ".venv", "__pycache__"}
            and not (Path(directory) / name).is_symlink()
        ]
        for name in files:
            path = Path(directory) / name
            if path.is_symlink():
                continue
            relative = path.relative_to(repo_root).as_posix()
            if relative in known:
                continue
            with path.open("rb") as stream:
                prefix = stream.read(65536)
            if prefix.startswith(marker) or (
                prefix.startswith(b"---\n") and b"\n---\n" + marker in prefix
            ):
                orphaned.append(relative)
    return sorted(orphaned)


def cmd_sync(args: argparse.Namespace) -> int:
    manifest = load_manifest(args.targets)
    for value in manifest.retired_outputs:
        out = retired_output_path(value, args.repo_root)
        if out.is_dir() and not out.is_symlink():
            raise PmError(f"retired output is a directory; refusing to remove it: {out}")
        if out.exists() or out.is_symlink():
            out.unlink()
            print(f"removed retired output -> {out}")
    for name, target in sorted(manifest.targets.items()):
        print(f"synced {name} -> {sync_target(target, args.pm_dir, args.repo_root)}")
    return 0


def cmd_lint(args: argparse.Namespace) -> int:
    manifest = load_manifest(args.targets)
    targets = manifest.targets
    drifted = [
        f"{name} ({state}) -> {target.output}"
        for name, target in sorted(targets.items())
        if (state := check_drift(target, args.pm_dir, args.repo_root)) != "ok"
    ]
    retired_present = [
        value
        for value in manifest.retired_outputs
        if (path := retired_output_path(value, args.repo_root)).exists() or path.is_symlink()
    ]
    orphaned = orphaned_generated_outputs(manifest, args.repo_root)
    if drifted or retired_present or orphaned:
        print("pm lint FAILED: generated docs are out of date.", file=sys.stderr)
        for line in drifted:
            print(f"  - {line}", file=sys.stderr)
        for value in retired_present:
            print(f"  - retired output still exists -> {value}", file=sys.stderr)
        for value in orphaned:
            print(f"  - generated output has no target or retirement -> {value}", file=sys.stderr)
        print("run `python3 tools/pm/pm.py sync`", file=sys.stderr)
        return 1
    print(f"pm lint OK: {len(targets)} target(s) up to date")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    manifest = load_manifest(args.targets)
    targets = manifest.targets
    print(f"{'TARGET':<14} {'STATE':<8} OUTPUT")
    for name, target in sorted(targets.items()):
        print(f"{name:<14} {check_drift(target, args.pm_dir, args.repo_root):<8} {target.output}")
    for value in manifest.retired_outputs:
        path = retired_output_path(value, args.repo_root)
        state = "present" if path.exists() or path.is_symlink() else "absent"
        print(f"{'retired':<14} {state:<8} {value}")
    return 0


def cmd_preview(args: argparse.Namespace) -> int:
    targets = load_targets(args.targets)
    if args.target not in targets:
        raise PmError(f"unknown target '{args.target}' (known: {', '.join(sorted(targets))})")
    sys.stdout.write(render_target(targets[args.target], args.pm_dir))
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="render agent guidance from canonical sources")
    parser.add_argument("--targets", type=Path, default=PM_DIR / "targets.json")
    parser.add_argument("--pm-dir", type=Path, default=PM_DIR)
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("sync").set_defaults(func=cmd_sync)
    sub.add_parser("lint").set_defaults(func=cmd_lint)
    sub.add_parser("status").set_defaults(func=cmd_status)
    preview = sub.add_parser("preview")
    preview.add_argument("--target", required=True)
    preview.set_defaults(func=cmd_preview)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except PmError as error:
        print(f"error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
